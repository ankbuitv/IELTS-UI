const CANARY = `CANARY-${RUN}-DO-NOT-LEAK`;

function buildReadingContent({ profileId, suffix }) {
  const groups = [];
  // `answers` holds server-only answer keys, `responses` the candidate replies
  // this script submits (the shapes differ: keys carry accepted alternatives).
  const answers = new Map();
  const responses = new Map();
  let number = 1;
  let questionId = 0;

  const nextId = () => `q_${suffix}_${(questionId += 1)}`;

  // 1-10 True / False / Not Given
  const tfngValues = ['TRUE', 'FALSE', 'NOT_GIVEN'];
  const tfngQuestions = [];
  for (let index = 0; index < 10; index += 1) {
    tfngQuestions.push({
      id: nextId(),
      number,
      prompt: `Statement ${number}: paragraph ${String.fromCharCode(65 + (index % 6))} describes study method ${index + 1}.`,
      options: [],
      config: {},
    });
    const value = tfngValues[index % 3];
    answers.set(number, {
      kind: 'CHOICE',
      values: [value],
      evidence: `${CANARY}: server-only marking evidence for question ${number}.`,
    });
    responses.set(number, { value });
    number += 1;
  }
  groups.push({
    type: 'TRUE_FALSE_NOT_GIVEN',
    instructions: 'Write TRUE, FALSE or NOT GIVEN.',
    sharedOptions: [],
    config: {},
    rangeFrom: 1,
    rangeTo: 10,
    questions: tfngQuestions,
  });

  // 11-20 multiple choice (single)
  const mcqQuestions = [];
  for (let index = 0; index < 10; index += 1) {
    const options = [
      { id: 'A', text: `Option A for ${number}` },
      { id: 'B', text: `Option B for ${number}` },
      { id: 'C', text: `Option C for ${number}` },
      { id: 'D', text: `Option D for ${number}` },
    ];
    const correct = ['A', 'B', 'C', 'D'][index % 4];
    mcqQuestions.push({ id: nextId(), number, prompt: `Choose the correct option for question ${number}.`, options, config: {} });
    answers.set(number, { kind: 'CHOICE', values: [correct] });
    responses.set(number, { value: correct });
    number += 1;
  }
  groups.push({
    type: 'MCQ_SINGLE',
    instructions: 'Choose the correct letter A, B, C or D.',
    sharedOptions: [],
    config: {},
    rangeFrom: 11,
    rangeTo: 20,
    questions: mcqQuestions,
  });

  // 21-30 short answer (text)
  const shortQuestions = [];
  for (let index = 0; index < 10; index += 1) {
    const word = `answer${index + 1}`;
    shortQuestions.push({
      id: nextId(),
      number,
      prompt: `Write one word for question ${number}.`,
      options: [],
      config: {},
    });
    answers.set(number, { kind: 'TEXT', accept: [word] });
    responses.set(number, { value: word });
    number += 1;
  }
  groups.push({
    type: 'SHORT_ANSWER',
    instructions: 'Write no more than one word for each answer.',
    sharedOptions: [],
    config: { wordLimit: { max: 1 } },
    rangeFrom: 21,
    rangeTo: 30,
    questions: shortQuestions,
  });

  // 31-40 sentence completion (text)
  const completionQuestions = [];
  for (let index = 0; index < 10; index += 1) {
    const word = `complete${index + 1}`;
    completionQuestions.push({
      id: nextId(),
      number,
      prompt: `Complete the sentence for question ${number}: the study group met each [[${number}]].`,
      options: [],
      config: {},
    });
    answers.set(number, { kind: 'TEXT', accept: [word] });
    responses.set(number, { value: word });
    number += 1;
  }
  groups.push({
    type: 'SENTENCE_COMPLETION',
    instructions: 'Complete the sentences with one word.',
    sharedOptions: [],
    config: { wordLimit: { max: 1 } },
    rangeFrom: 31,
    rangeTo: 40,
    questions: completionQuestions,
  });

  // Attach the server-only answer material to each question. The worker stores
  // `answerKey`/`evidence`/`explanation` in `answer_keys` and never returns them
  // to a candidate payload (asserted below).
  for (const group of groups) {
    for (const question of group.questions) {
      const key = answers.get(question.number);
      question.answerKey = { kind: key.kind, ...(key.values ? { values: key.values } : {}), ...(key.accept ? { accept: key.accept } : {}) };
      question.evidence = key.evidence ?? null;
    }
  }

  const content = {
    sections: [
      {
        skill: 'READING',
        title: `Integration Reading Passage ${suffix}`,
        subtitle: 'Generated by scripts/integration.mjs',
        instructions: 'Read the passage and answer questions 1 to 40.',
        durationSeconds: 1800,
        passage: {
          title: `Integration Passage ${suffix}`,
          subtitle: null,
          paragraphs: [
            { label: 'A', text: 'Paragraph A of the integration fixture. It exists only to give the questions context.' },
            { label: 'B', text: 'Paragraph B describes a method, a cause and a consequence in plain language.' },
            { label: 'C', text: 'Paragraph C offers a qualification to the claim made in paragraph B.' },
            { label: 'D', text: 'Paragraph D compares two approaches without recommending either.' },
            { label: 'E', text: 'Paragraph E discusses cost, staffing and scheduling.' },
            { label: 'F', text: 'Paragraph F summarises the argument.' },
          ],
        },
        audioAssetId: null,
        playback: {},
        groups,
      },
    ],
    durationSeconds: 1800,
    isCompleteTest: true,
    scoringProfileId: profileId,
  };

  return { content, answers, responses };
}

