#!/usr/bin/env node
/**
 * End-to-end acceptance script for the V1 platform.
 *
 * It drives a running Worker over real HTTP (cookies, CSRF headers, JSON) and
 * exercises four flows:
 *
 *   1. ADMIN      — create a 40-question Reading test, validate, publish, preview
 *   2. TEACHER    — classroom, enrolment, assignment, reports, cross-classroom IDOR check
 *   3. STUDENT    — assignment attempt, autosave, integrity events, submit, marked result
 *   4. FULL MOCK  — multi-component sequence, section advance, submit
 *
 * Usage:
 *   npm run dev                     # in one terminal (Worker on :8787)
 *   npm run test:integration        # in another
 *
 * Environment:
 *   BASE_URL        default http://127.0.0.1:8787
 *   ADMIN_EMAIL     optional: log in as an existing admin instead of bootstrapping
 *   ADMIN_PASSWORD  required when ADMIN_EMAIL is set
 *
 * The script only talks to the public API: it never touches D1 directly.
 */
import process from 'node:process';

const BASE_URL = (process.env.BASE_URL ?? 'http://127.0.0.1:8787').replace(/\/$/, '');
const RUN = Date.now().toString(36);
const PASSWORD = 'Integration-Passw0rd!23';

let passed = 0;
let failed = 0;
const failures = [];

function assert(condition, message) {
  if (condition) {
    passed += 1;
    console.log(`    ✓ ${message}`);
  } else {
    failed += 1;
    failures.push(message);
    console.error(`    ✗ ${message}`);
  }
}

function section(title) {
  console.log(`\n${title}`);
}

/** Minimal cookie-jar HTTP client: one instance per signed-in identity. */
function createClient(label) {
  const cookies = new Map();
  let csrfToken = null;

  async function request(method, path, body, options = {}) {
    const headers = new Headers();
    if (cookies.size > 0) {
      headers.set('cookie', [...cookies.entries()].map(([name, value]) => `${name}=${value}`).join('; '));
    }
    headers.set('origin', BASE_URL);
    if (csrfToken && method !== 'GET' && method !== 'HEAD') headers.set('x-csrf-token', csrfToken);

    let payload;
    if (body instanceof FormData) {
      payload = body;
    } else if (body !== undefined) {
      headers.set('content-type', 'application/json');
      payload = JSON.stringify(body);
    }

    const response = await fetch(`${BASE_URL}${path}`, { method, headers, body: payload, redirect: 'manual' });

    const setCookie = response.headers.getSetCookie?.() ?? [];
    for (const cookie of setCookie) {
      const [pair] = cookie.split(';');
      const index = pair.indexOf('=');
      const name = pair.slice(0, index);
      const value = pair.slice(index + 1);
      if (value === '' ) cookies.delete(name);
      else cookies.set(name, value);
    }

    const text = await response.text();
    let json = null;
    if (text) {
      try {
        json = JSON.parse(text);
      } catch {
        json = null;
      }
    }

    if (!options.expectStatuses?.includes(response.status) && !response.ok) {
      throw new Error(`${label} ${method} ${path} -> ${response.status} ${text.slice(0, 300)}`);
    }

    return { status: response.status, body: json, text };
  }

  return {
    label,
    get: (path, options) => request('GET', path, undefined, options),
    post: (path, body, options) => request('POST', path, body ?? {}, options),
    put: (path, body, options) => request('PUT', path, body ?? {}, options),
    patch: (path, body, options) => request('PATCH', path, body ?? {}, options),
    delete: (path, options) => request('DELETE', path, undefined, options),
    setCsrfToken(token) {
      csrfToken = token;
    },
    async register(email, displayName, bootstrapAdmin = false) {
      const result = await request('POST', '/api/auth/register', { email, password: PASSWORD, displayName, bootstrapAdmin });
      csrfToken = result.body?.csrfToken ?? null;
      return result.body?.user;
    },
    async login(email) {
      const result = await request('POST', '/api/auth/login', { email, password: PASSWORD });
      csrfToken = result.body?.csrfToken ?? null;
      return result.body?.user;
    },
  };
}

